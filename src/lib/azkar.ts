const evening: Zikr[] = morning.map(z => {
  // Adapt morning adhkar to evening wording
  let text = z.text
    .replace(/أَصْبَحْنَا/g, 'أَمْسَيْنَا')
    .replace(/أَصْبَحَ الْمُلْكُ/g, 'أَمْسَى الْمُلْكُ')
    .replace(/هَذَا الْيَوْمِ/g, 'هَذِهِ اللَّيْلَةِ')
    .replace(/خَيْرَ مَا بَعْدَهُ/g, 'خَيْرَ مَا بَعْدَهَا')
    .replace(/شَرِّ مَا بَعْدَهُ/g, 'شَرِّ مَا بَعْدَهَا');
  return { ...z, id: z.id.replace(/^m-/, 'e-'), text };
});

